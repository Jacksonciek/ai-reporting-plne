def clean_code(raw_code: str):
    """Clean up code generated by an LLM"""
    pattern = re.compile(r"```python\s*([\s\S]+?)\s*```", re.MULTILINE)
    code_blocks = pattern.findall(raw_code)
    code_blocks_combined = "\n".join(code_blocks)
    return code_blocks_combined
